#ifndef MOONLIGHT_ENET_UTILITY_H
#define MOONLIGHT_ENET_UTILITY_H

#define ENET_MAX(x, y) ((x) > (y) ? (x) : (y))
#define ENET_MIN(x, y) ((x) < (y) ? (x) : (y))
#define ENET_DIFFERENCE(x, y) ((x) < (y) ? (y) - (x) : (x) - (y))

#endif /* MOONLIGHT_ENET_UTILITY_H */

